// Combine all fields
export const ALL_PREDEFINED_FIELDS: PredefinedFieldItem[] = [
  ...SYSTEM_FIELDS,
  ...DEFAULT_CUSTOM_FIELDS,
];

// Function to get predefined fields tailored for a specific selected industry
export function getPredefinedFieldsForIndustry(
  selectedIndustry?: string
): PredefinedFieldItem[] {
  if (!selectedIndustry || selectedIndustry.includes('General') || selectedIndustry.includes('Universal') || selectedIndustry === 'All') {
    return ALL_PREDEFINED_FIELDS;
  }

  const cleanSelected = selectedIndustry.toLowerCase().trim();

  return ALL_PREDEFINED_FIELDS.filter((item) => {
    if (!item.industry || item.industry === 'All') return true;
    const cleanItemIndustry = item.industry.toLowerCase().trim();
    return (
      cleanItemIndustry === cleanSelected ||
      cleanSelected.includes(cleanItemIndustry) ||
      cleanItemIndustry.includes(cleanSelected)
    );
  });
}

// Helper to convert a PredefinedFieldItem into a FormFieldTemplate instance
export function createFormFieldFromPredefined(
  item: PredefinedFieldItem
): FormFieldTemplate {
  const uniqueSuffix = Math.floor(1000 + Math.random() * 9000);
  return {
    id: `f-${item.key}-${Date.now()}-${uniqueSuffix}`,
    label: item.label,
    name: `${item.key}_${uniqueSuffix}`,
    type: item.type,
    placeholder: item.placeholder || '',
    helperText: item.helperText || item.description || '',
    isRequired: item.isRequired || false,
    options: item.options ? [...item.options] : undefined,
    crmFieldMapping: item.crmFieldMapping || item.key,
    fieldSource: item.category === 'System' ? 'system' : 'custom',
    sourceModule: item.module,
    systemFieldKey: item.key,
  };
}
